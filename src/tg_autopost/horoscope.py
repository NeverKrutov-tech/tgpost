def _make_rng(sign_index: int) -> random.Random:
    day = datetime.date.today().toordinal()
    return random.Random(day * 100 + sign_index)


def generate_horoscope() -> str:
    day_name = datetime.datetime.today().strftime("%A").lower()
    day_names_ru = {
        "monday": "Понедельник", "tuesday": "Вторник", "wednesday": "Среда",
        "thursday": "Четверг", "friday": "Пятница", "saturday": "Суббота",
        "sunday": "Воскресенье",
    }
    day_ru = day_names_ru.get(day_name, "Сегодня")

    lines = [
        f"🌌 <b>Гороскоп от @Anetdodik</b> — {day_ru.lower()}, "
        f"ещё один день для подвигов (или лени)\n"
    ]

    for idx, (emoji, sign_name) in enumerate(SIGNS):
        rng = _make_rng(idx)
        preds = NEW_PREDICTIONS[sign_name]
        prediction = preds[rng.randint(0, len(preds) - 1)]
        advice = rng.choice(ADVICE)
        lines.append(
            f"{emoji} <b>{sign_name}</b>\n"
            f"💢 {sign_name}, сегодня ты {prediction}.\n"
            f"🪴 Совет: {advice}\n"
            f"‣\n"
        )

    lines.append(
        f"💠 <i>Гороскоп не настоящий, но какой из них вообще настоящий? "
        f"Подпишись на @Anetdodik — звёзды велят!</i>"
    )

    return "\n".join(lines)
